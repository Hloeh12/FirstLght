const ZODIAC_ANIMAL={'子':'鼠','丑':'牛','寅':'虎','卯':'兔','辰':'龙','巳':'蛇','午':'马','未':'羊','申':'猴','酉':'鸡','戌':'狗','亥':'猪'};

function readingOf(input){
 if(input&&Array.isArray(input.pillars)&&input.strength)return input; // 已是排盘结果
 const birth=input?.birth||input;
 return baziPro({birth});
}
function profileOf(input){const p=input?.birth?input:{birth:input};return{surname:p.surname||'',gender:p.gender||'',birth:p.birth};}

function wuge(surname, given){
 const s=surname.split('').map(strokeOf),g=given.split('').map(strokeOf);
 const sky=s.length===1?s[0]+1:s[0]+s[1]; // 单姓天格=姓+1
 const person=s[0]+g[0];
 const land=g.length===1?g[0]+1:g.reduce((a,b)=>a+b,0);
 const total=s.reduce((a,b)=>a+b,0)+g.reduce((a,b)=>a+b,0);
 const outer=total-person+1;
 const items={天格:sky,人格:person,地格:land,总格:total,外格:outer};
 const detail=Object.entries(items).map(([k,v])=>({ge:k,num:v,luck:numLuck(v)}));
 // 三才：天人地三格末位数字对应的五行生克
 const se=[EL_OF_DIGIT(sky%10),EL_OF_DIGIT(person%10),EL_OF_DIGIT(land%10)];
 let sc=3;const pair=(a,b)=>a===b?'比和':PRODUCE[a]===b?'相生':CONTROL[a]===b?'相克':'被克';
 const rel1=pair(se[0],se[1]),rel2=pair(se[1],se[2]);
 sc=({比和:4,相生:5,相克:1,被克:2})[rel1]+({比和:4,相生:5,相克:1,被克:2})[rel2]-2;
 return {items,detail,sancai:se.join('')+'（'+rel1+'·'+rel2+'）',sancaiScore:Math.max(0,sc)};
}
function toneOf(py){const t='āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ';for(let i=0;i<py.length;i++){const idx=t.indexOf(py[i]);if(idx>=0)return idx%4;}return 0;}

function scoreName(name, useful, caution, yearBranch, surname){
 const chars=name.given.split('').map(c=>BY_CHAR.get(c));
 const eleScore=chars.reduce((a,c)=>{
  if(useful.includes(c.el))return a+10;
  if(useful.some(u=>PRODUCE[c.el]===u))return a+6; // 生助喜用
  if(caution.includes(c.el))return a+0;
  return a+3;
 },0)/chars.length*4; // 40 满分
 const wg=wuge(surname,name.given);
 const gridScore=Math.min(25,wg.detail.reduce((a,d)=>a+NUM_SCORE[d.luck],0)*1.25+wg.sancaiScore); // 25 满分
 const z=ZODIAC[yearBranch]||[];
 const zodiacScore=chars.reduce((a,c)=>a+(z.includes(c.el)?5:2),0)/2; // 10 满分
 const tones=name.given.split('').map(c=>toneOf(BY_CHAR.get(c).py));
 const diversity=new Set(tones).size;
 let phono=diversity===tones.length?15:diversity>1?11:6; // 声调各不相同>声调有变化>全同调
 const tagBonus=chars.reduce((a,c)=>a+Math.min(c.tags.length,3),0);
 const genderFit=chars.every(c=>!c.g||name.gender==='女'?c.g!=='m':name.gender==='男'?c.g!=='f':true)?3:0;
 const meanScore=Math.min(10,5+tagBonus*0.8+genderFit);
 const total=Math.min(100,Math.round((eleScore+gridScore+zodiacScore+phono+meanScore)*10)/10);
 return {eleScore,gridScore,zodiacScore,phono,meanScore,total,wg};
}
function reasons(r,wg,useful,caution,yearBranch){
 const out=[];
 out.push(`五行：名字用字以${useful.join('、')}为喜用，契合扶抑喜用（忌${caution.join('、')}）。`);
 out.push(`数理：${wg.detail.map(d=>d.ge+d.num+'（'+d.luck+'）').join('、')}；三才${wg.sancai}。`);
 out.push(`生肖：年支${ZODIAC_ANIMAL[yearBranch]||yearBranch}，宜${(ZODIAC[yearBranch]||[]).join('、')}，用字多合。`);
 out.push(`音律：声调搭配${r.dims.phonology>=15?'错落有致，朗朗上口':r.dims.phonology>=11?'有起伏，读来顺口':'平缓，但整体顺口'}。`);
 out.push(`寓意：${r.name.slice(r.name.length-r.given.length).split('').map(c=>c+'（'+BY_CHAR.get(c).tags.join('、')+'）').join('')}。`);
 return out;
}
export function suggestNames(input,opts={}){
 const reading=readingOf(input),{surname,gender,birth}=profileOf(input);
 const surname2=surname||'李';
 const useful=reading.strength?.useful||[],caution=reading.strength?.caution||[];
 const yearBranch=reading.pillars?.[0]?.branch||'子';
 const count=opts.count||8,len=opts.length||2;
 const pool=[...NAMING_CHARS].sort((a,b)=>(useful.includes(b.el)?1:0)-(useful.includes(a.el)?1:0));
 const firsts=pool.slice(0,30),results=[];
 const seen=new Set();
 for(const a of firsts){
  for(const b of NAMING_CHARS){
   if(len===2&&a.ch===b.ch)continue;
   const given=len===1?a.ch:a.ch+b.ch;
   if(seen.has(given))continue;seen.add(given);
   const py=len===1?a.py:a.py+' '+b.py;
   const score=scoreName({given,gender},useful,caution,yearBranch,surname2);
   results.push({name:surname2+given,given,pinyin:py,total:score.total,
    dims:{element:Math.round(score.eleScore*10)/10,wuge:Math.round(score.gridScore*10)/10,zodiac:Math.round(score.zodiacScore*10)/10,phonology:score.phono,meaning:Math.round(score.meanScore*10)/10},_wg:score.wg});
   if(results.length>200)break;
  }
  if(results.length>200)break;
 }
 results.sort((x,y)=>y.total-x.total);
 const pick=results.slice(0,count).map(({_wg,...x})=>({...x,reasons:reasons(x,_wg,useful,caution,yearBranch)}));
 return {surname:surname2,gender,useful,caution,yearBranch,zodiac:ZODIAC_ANIMAL[yearBranch]||yearBranch,
  list:pick};
}

