/** 取日干×月支的调候用神（返回五行与天干）。无表则用通用寒暖规则兜底。 */
export function tiaoHouUse(dayStem,monthBranch){
 const raw=TIAO_HOU[dayStem]?.[monthBranch];
 const season=SEASON[monthBranch]||'温';
 if(!raw?.length){
  // 兜底：寒月通用取火（丙），燥月通用取水（壬），温凉月以日干生扶为用
  const fallback=season==='寒'?'丙':season==='燥'?'壬':resourceOf(elemOfStem(dayStem))==='水'?'壬':'丙';
  return {gods:[fallback],elements:[elemOfStem(fallback)],season,source:'通用寒暖兜底（该日干×月支未列专门调候表）'};
 }
 return {gods:[...raw],elements:[...new Set(raw.map(elemOfStem))],season,
  source:`《穷通宝鉴》${dayStem}生${monthBranch}月调候代表用神（通行精简口径）`};
}

/** 从格判定：某一五行权重占比过高、日主无本气根、且无有效印比生扶时，顺其势。
 *  weights: {五行:数值}；roots: 地支本气根五行数组；dayStem: 日干。
 * 返回 null 表示不构成从格（仍按扶抑）。 */
export function detectCongGe(weights,roots,dayStem){
 const total=Object.values(weights).reduce((a,b)=>a+b,0);
 if(!total)return null;
 const self=elemOfStem(dayStem),res=resourceOf(self);
 const entries=Object.entries(weights).sort((a,b)=>b[1]-a[1]);
 const [topElem,topVal]=entries[0];
 const ratio=topVal/total;
 const hasRoot=roots.includes(self);
 const helper=weights[self]+(weights[res]||0); // 同我+生我
 const helperRatio=helper/total;
 // 从财：财星成势；从杀：官杀成势；从儿：食伤成势。财=我克、杀=克我、儿=我生
 const kind=topElem===control[self]?'从财':topElem===Object.keys(control).find(k=>control[k]===self)?'从杀':topElem===produce[self]?'从儿':null;
 if(!kind||ratio<0.70||hasRoot||helperRatio>0.15)return null;
 return {kind,element:topElem,ratio:+(ratio*100).toFixed(1),helperRatio:+(helperRatio*100).toFixed(1),
  use:[topElem,produce[topElem]],note:`${kind}格：${topElem}成势（占 ${(ratio*100).toFixed(0)}%），日主无本气根、印比仅 ${(helperRatio*100).toFixed(0)}%；顺势以${topElem}与其所生${produce[topElem]}为用，不逆势扶抑。`};
}
