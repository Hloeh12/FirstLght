// 合并搜索：中文名或英文名前缀/包含匹配（不区分大小写）。与 geo.mjs 的中国库互补。
export function searchWorldCities(query,limit=8){
 const q=String(query||'').trim().toLowerCase();
 if(!q)return [];
 const out=[];
 for(const c of WORLD_CITIES){
  if(c.name.toLowerCase().includes(q)||c.nameEn.toLowerCase().includes(q)||c.country.toLowerCase().includes(q))out.push(c);
  if(out.length>=limit)break;
 }
 return out;
}
