import test from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM,VirtualConsole} from 'jsdom';
import {buildSync} from 'esbuild';
import {spawn} from 'node:child_process';
import {mkdtempSync,readFileSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';

test('new routed console drives the shared case, chart tools and contextual sheets',async t=>{
 const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'18767',DATA_DIR:mkdtempSync(path.join(os.tmpdir(),'firstlight-console-'))},stdio:['ignore','pipe','pipe']});
 t.after(()=>server.kill());
 await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('server exited '+code)));});
 const base='http://127.0.0.1:18767';
 const js=buildSync({entryPoints:['assets/console/app.js'],bundle:true,write:false,format:'iife'}).outputFiles[0].text;
 const errors=[],vc=new VirtualConsole();vc.on('jsdomError',e=>errors.push(e.message));
 const dom=new JSDOM(readFileSync('index.html','utf8'),{url:base,runScripts:'dangerously',virtualConsole:vc,beforeParse(w){
  w.fetch=(url,opts)=>fetch(new URL(url,base),{...opts,signal:undefined});w.scrollTo=()=>{};
 }});
 t.after(()=>dom.window.close());
 const w=dom.window,doc=w.document;
 const script=doc.createElement('script');script.textContent=js;doc.body.append(script);
 const $=s=>doc.querySelector(s),many=s=>[...doc.querySelectorAll(s)];
 const click=s=>{const b=$(s);assert(b,s);b.click();};
 const until=async(predicate,label)=>{
  for(let i=0;i<150&&!predicate();i++)await new Promise(r=>setTimeout(r,60));
  assert(predicate(),label+' | '+($('#birthStatus')?.textContent||'')+' | '+($('#screen')?.textContent||'').slice(0,180));
 };
 assert($('#birthSheet').open);
 assert(!$('#screen').querySelector('form'));
 let form=$('#birthForm');
 for(const [k,v] of Object.entries({name:'测试案例',date:'1998-11-21',clock:'00:02',lat:'30.361448',lon:'109.492552',tz:'8'}))form.elements[k].value=v;
 assert.equal(form.elements.city.required,false);
 click('#birthForm [type=submit]');
 await until(()=>Boolean($('.zi-board')),'first chart');
 assert(!$('#birthSheet').open);
 assert.equal(many('[data-palace]').length,12);
 assert($('#activeProfile').textContent.includes('测试案例'));
 assert.equal(JSON.parse(w.localStorage.getItem('xy_active_profile')).name,'测试案例');
 assert.equal(many('.zi-triad').length,1);
 click('[data-mode=flying]');
 assert.equal(many('.flying-arc[marker-end]').length,4);
 click('[data-mode=transform]');
 assert(many('.zi-cell.transform').length>0);
 click('[data-rail=大限]');
 await until(()=>$('#screen').textContent.includes('大限')&&Boolean($('.zi-flow')),'decadal');
 click('[data-rail=流年]:nth-child(2)');
 await until(()=>many('[data-rail=流月]').length>=12,'yearly');
 click('[data-rail=流月]');
 await until(()=>many('[data-rail=流日]').length>=29,'monthly');
 click('[data-rail=流日]:nth-child(3)');
 await until(()=>$('.zi-detail h2')?.textContent.includes('流日'),'daily');
 assert.equal(many('.zi-flow').length,3);
 click('[data-badge=period]');
 assert($('#termSheet').open);
 click('#termSheet [data-close]');
 click('#toolsButton');click('[data-type=earth]');
 await until(()=>$('.zi-center')?.textContent.includes('地盘'),'earth chart');
 click('#caseDrawerButton');assert($('#caseDrawer').open);
 click('[data-tab=cases]');assert(!$('#caseDrawer').open);
 assert($('#caseGroups').textContent.includes('新建分组'));
 assert(!$('#caseGroups').textContent.includes('客户'));
 click('[data-action=use]');
 await until(()=>Boolean($('.zi-board')),'case activation');
 click('#toolsButton');click('[data-system=bazi]');
 assert.equal(many('.pillar').length,4);
 assert(many('.pillar .term').length>14);
 click('[data-combine]');
 await until(()=> $('[data-combine]')?.getAttribute('aria-pressed')==='true','bazi combine');
 click('#toolsButton');
 assert.equal(many('[data-bazi-tool]').length,6);
 click('[data-bazi-tool="3"]');
 await until(()=>$('#toolSheet').textContent.includes('两'),'bone panel');
 click('#toolSheet [data-close]');click('#toolsButton');click('[data-system=west]');
 await until(()=>Boolean($('.wheel')),'western wheel');
 click('[data-mode=transit]');
 await until(()=>$('.wheel')?.getAttribute('aria-label').includes('双圈'),'transit wheel');
 click('#toolsButton');click('[data-astro-config]');
 assert.equal(many('[name=house] option').length,7);
 $('[name=house]').value='campanus';
 $('[name=house]').dispatchEvent(new w.Event('change',{bubbles:true}));
 await until(()=>$('#screen').textContent.includes('Campanus'),'house recompute');
 assert.equal(JSON.parse(w.localStorage.getItem('xy_astro_config')).house,'campanus');
 click('#toolSheet [data-close]');click('[data-tab=insights]');
 assert($('#screen').textContent.includes('全生命周期'));
 assert(!$('.zi-board'));
 assert.deepEqual(errors,[]);
});
